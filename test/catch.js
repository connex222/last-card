'use strict';
const assert = require('node:assert/strict');
const { CatchWindow } = require('../game/catch');
let now = 1000;
const w = new CatchWindow({clock: () => now});
let penalties = 0;
const penalise = (offender, catcher) => { assert.equal(offender,'a'); assert.equal(catcher,'b'); penalties++; };
w.open('a',['a','b','c']);
assert.equal(w.resolve('a','catch',penalise).reason,'not_eligible');
assert.equal(w.resolve('outsider','catch',penalise).reason,'not_eligible');
assert.equal(w.resolve('b','call',penalise).reason,'not_offender');
assert.equal(w.resolve('a','call',penalise).outcome,'saved');
assert.equal(w.resolve('b','catch',penalise).reason,'closed');
assert.equal(penalties,0);
w.open('a',['b','c']);
assert.equal(w.resolve('b','catch',penalise).outcome,'caught');
assert.equal(w.resolve('c','catch',penalise).reason,'closed');
assert.equal(penalties,1);
w.open('a',['b']); now += 4000;
assert.equal(w.resolve('b','catch',penalise).reason,'expired');
assert.equal(penalties,1);
assert.throws(() => new CatchWindow({durationMs:4001}),RangeError);
console.log('CATCH! arbitration tests passed');
